# 地点条目的权威来源：data.js（首次由 index.html 生成，之后自更新）
DATA = os.path.join(ROOT, "data.js")
src = open(DATA, encoding="utf-8").read()
rows = json.loads(src[src.index("const D=") + 8: src.rindex(";")])

# 优先用已下载到本地的照片；没有本地副本时才回落到远程 URL
LOCAL = os.path.join(HERE, "photos_local.json")
if os.path.exists(LOCAL):
    raw = json.load(open(LOCAL, encoding="utf-8"))
    # photos/<hash>_s.jpg / _l.jpg  ->  统一成带 {W} 的模板
    photos = {k: {"u": v["s"].replace("_s.jpg", "_{W}.jpg"), "f": v["f"]}
              for k, v in raw.items()}
    print("使用本地照片:", len(photos), "组")
else:
    photos = json.load(open(os.path.join(HERE, "photos.json"), encoding="utf-8"))
    print("未找到本地照片，回落到维基远程 URL")
china = json.load(open(os.path.join(HERE, "china.json"), encoding="utf-8"))
TERMS = os.path.join(HERE, "terms.json")
terms = json.load(open(TERMS, encoding="utf-8")) if os.path.exists(TERMS) else {}

places, nocoord, nophoto = [], [], 0
for r in rows:
    o = {k: r[k] for k in ("k", "t", "n", "pv", "a", "pl", "m", "mo", "d", "w") if k in r}
    if r.get("hot"):
        o["hot"] = 1
    ll = C.get(o["n"])
    if ll:
        o["ll"] = ll
    else:
        nocoord.append(o["n"])
    t = terms.get(o["n"])
    if t and t != o["n"]:
        o["q"] = t            # 外链检索词，与显示名不同时才存
    ph = photos.get(o["n"])
    if ph:
        o["img"] = ph["u"]          # 含 {W} 占位符，页面按用途替换宽度
        o["cr"] = ph["f"]
    else:
        nophoto += 1
    places.append(o)

out = os.path.join(ROOT, "data.js")
with open(out, "w", encoding="utf-8") as f:
    f.write("/* 自动生成，勿手改。源：build/coords.py */\n")
    f.write("const CHINA=" + json.dumps(china, ensure_ascii=False, separators=(",", ":")) + ";\n")
    f.write("const D=" + json.dumps(places, ensure_ascii=False, separators=(",", ":")) + ";\n")

print(f"地点 {len(places)}｜有坐标 {len(places)-len(nocoord)}｜有实景照 {len(places)-nophoto}"
      f"｜省界 {len(china['p'])} 个\n输出 {out}  {os.path.getsize(out)/1024:.0f}KB")
if nocoord:
    print("缺坐标:", nocoord)
